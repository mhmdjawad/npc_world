<?php
$db_host = getenv('DB_HOST') ?: 'mysql';
$db_port = getenv('DB_PORT') ?: '3306';
$db_user = getenv('DB_USER') ?: 'npcworld';
$db_password = getenv('DB_PASSWORD') ?: 'npcworld_password';
$db_name = getenv('DB_NAME') ?: 'npcworld';

$conn = new mysqli($db_host, $db_user, $db_password, $db_name, $db_port);

if ($conn->connect_error) {
    die("Connection failed: " . $conn->connect_error);
}

$message = '';
$error = '';

if ($_SERVER['REQUEST_METHOD'] === 'POST') {
    $username = $conn->real_escape_string($_POST['username']);
    $email = $conn->real_escape_string($_POST['email']);
    $password = $_POST['password'];
    
    if (empty($username) || empty($email) || empty($password)) {
        $error = 'All fields are required';
    } else {
        $password_hash = password_hash($password, PASSWORD_DEFAULT);
        
        $sql = "INSERT INTO players (username, email, password_hash) VALUES (?, ?, ?)";
        $stmt = $conn->prepare($sql);
        $stmt->bind_param("sss", $username, $email, $password_hash);
        
        if ($stmt->execute()) {
            $player_id = $stmt->insert_id;
            $message = "Registration successful! Player ID: " . $player_id;
        } else {
            if ($conn->errno === 1062) {
                $error = "Username or email already exists";
            } else {
                $error = "Registration failed: " . $conn->error;
            }
        }
        
        $stmt->close();
    }
}

$conn->close();
